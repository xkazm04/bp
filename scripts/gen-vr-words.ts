// The VR light table's copy of the web's words that no API route carries (spark vr-room-layers WP3): what a severity tier
// says (TIER_SAYS, packages/core/src/scan/derive.ts, the queue's tier chip) and a bay kind's name (BAY_KIND_NAME,
// packages/core/src/model/layout.ts). The lens names and the metric labels are not here: they come with the product's
// /structure answer (lenses[].manifest), which BpLink reads, so the manifest stays their one source.
// Writes apps/vr/Source/bp/BpWords.generated.h from core; a change to the words is made in core and this is run again.
// Run: node --import @bp/core/register scripts/gen-vr-words.ts           (write)
//      node --import @bp/core/register scripts/gen-vr-words.ts --check   (exit 1 when the committed header is stale;
//      npm run check:vr-words, part of npm run check)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TIER_SAYS } from '../packages/core/src/scan/derive.ts';
import { BAY_KINDS, BAY_KIND_NAME } from '../packages/core/src/model/layout.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'apps/vr/Source/bp/BpWords.generated.h');

const lit = (s: string) => 'TEXT("' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '")';

export function header(): string {
  return [
    '// Generated by scripts/gen-vr-words.ts from packages/core: do not edit. Change the words in core, then run',
    '// `node --import @bp/core/register scripts/gen-vr-words.ts`; `npm run check:vr-words` fails while this file is stale.',
    '#pragma once',
    '',
    '#include "CoreMinimal.h"',
    '',
    'namespace BpWordsGenerated',
    '{',
    '\t/** TIER_SAYS (packages/core/src/scan/derive.ts): what a severity tier 0..3 says. */',
    `\tinline const TCHAR* const TierSays[${TIER_SAYS.length}] = { ${TIER_SAYS.map(lit).join(', ')} };`,
    '',
    '\t/** BAY_KIND_NAME (packages/core/src/model/layout.ts): a bay kind\'s name, in BAY_KINDS order. */',
    '\tstruct FKindName',
    '\t{',
    '\t\tconst TCHAR* Kind;',
    '\t\tconst TCHAR* Name;',
    '\t};',
    `\tinline const FKindName KindNames[${BAY_KINDS.length}] = {`,
    ...BAY_KINDS.map((k, i) => `\t\t{ ${lit(k)}, ${lit(BAY_KIND_NAME[k])} }${i + 1 < BAY_KINDS.length ? ',' : ''}`),
    '\t};',
    '}',
    '',
  ].join('\n');
}

const fresh = header();
if (process.argv.includes('--check')) {
  const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  const ok = committed === fresh;
  console.log(`${ok ? 'ok  ' : 'FAIL'}  apps/vr/Source/bp/BpWords.generated.h matches core's TIER_SAYS (${TIER_SAYS.length}) and BAY_KIND_NAME (${BAY_KINDS.length})${ok ? '' : committed === null ? ': missing' : ': stale, run node --import @bp/core/register scripts/gen-vr-words.ts'}`);
  // permanent control: a header with one word changed is told apart
  const control = fresh.replace(lit(TIER_SAYS[1]), lit(TIER_SAYS[1] + 'x')) !== fresh;
  console.log(`${control ? 'ok  ' : 'FAIL'}  control: a header with one tier word changed differs from a fresh one`);
  process.exit(ok && control ? 0 : 1);
}
fs.writeFileSync(OUT, fresh);
console.log(`wrote ${path.relative(ROOT, OUT)}`);
