#!/usr/bin/env node
// The art-pipeline scripts' local guards: no Blender, no ComfyUI, no Leonardo, no network beyond a loopback stub.
//   trellis-seed   trellis_run.mjs refuses a missing or non-integer seed before it touches the queue
//   writer-notes   write-manifests.mjs names the asset that has no NOTES entry instead of dereferencing undefined
//   paths          no script under scripts/art/ names an absolute machine path (provenance strings excepted)
//   writer-exit    write-manifests.mjs exits non-zero when a gate it wrote is false
// The writer cases run a COPY of write-manifests.mjs in a scratch root against a stub score-assets.mjs: nothing under
// apps/vr/ArtSource is read or written, so no manifest (and no lynx_commit) is ever regenerated by this check.
// Run: node scripts/art/check-art-scripts.mjs   Exit 1 on any failure.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));

let failed = 0;
const check = (name, ok, detail = '') => { if (!ok) failed++; console.log(`${ok ? 'ok  ' : 'FAIL'}  ${name}${ok || !detail ? '' : `  (${detail})`}`); };

// A port nothing listens on. NEVER leave BP_COMFY_URL unset in a run of this file: the owner's ComfyUI may be up on
// 8188, and a script that is not refused submits a real GPU job to it.
const deadPort = await new Promise((res) => { const sv = net.createServer(); sv.listen(0, '127.0.0.1', () => { const { port } = sv.address(); sv.close(() => res(port)); }); });
const DEAD = `http://127.0.0.1:${deadPort}`;

const TRELLIS = path.join(HERE, 'lamp', 'trellis_run.mjs');
for (const args of [[], ['abc'], ['1.5'], ['']]) {
  // No ComfyUI answers here: an unvalidated seed gets past the argument line and dies on the first fetch, so a
  // run that is refused FOR THE SEED says so by name and a run that is not says something else.
  const r = spawnSync(process.execPath, [TRELLIS, ...args], { encoding: 'utf8', timeout: 20000, env: { ...process.env, BP_COMFY_URL: DEAD } });
  check(`trellis-seed: argv ${JSON.stringify(args)} is refused by name`, r.status !== 0 && /seed must be an integer/.test(r.stderr ?? ''), `exit ${r.status}, stderr: ${(r.stderr ?? '').split('\n').find(Boolean) ?? ''}`);
}

// ---- write-manifests.mjs, in a scratch root ---------------------------------------------------------------------
const stub = `export const ASSETS = Object.fromEntries((process.env.STUB_IDS || 'survey-pin,fixture-kit').split(',').map((id) => [id, {}]));
export function scoreAsset(id) {
  const fail = (process.env.STUB_FAIL || '').split(',').filter(Boolean);
  const checks = Object.fromEntries(['meshes_present', 'no_floaters', 'one_uv_set', 'pivot', 'scale', 'materials', 'poly_budget', 'file_size'].map((k) => [k, !fail.includes(k)]));
  const meshes = ['a', 'b'].map((name) => ({ name, tris: 10, vertices: 8, components: 1, floaters: 0, bounds_cm: { x: 1, y: 2, z: 3 } }));
  return { id, class: 'stub', budget_tris: 100, tris_total: 20, meshes, materials: ['m1', 'm2'], checks, bytes: 1, pass: Object.values(checks).every(Boolean) };
}
`;
function runWriter(env, ids = ['survey-pin', 'fixture-kit']) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bp-art-writer-'));
  try {
    fs.mkdirSync(path.join(root, 'scripts', 'art'), { recursive: true });
    fs.copyFileSync(path.join(HERE, 'write-manifests.mjs'), path.join(root, 'scripts', 'art', 'write-manifests.mjs'));
    fs.writeFileSync(path.join(root, 'scripts', 'art', 'score-assets.mjs'), stub);
    for (const id of ids) { fs.mkdirSync(path.join(root, 'apps', 'vr', 'ArtSource', id), { recursive: true }); fs.writeFileSync(path.join(root, 'apps', 'vr', 'ArtSource', id, 'final.glb'), 'x'); }
    const r = spawnSync(process.execPath, [path.join(root, 'scripts', 'art', 'write-manifests.mjs')], { encoding: 'utf8', timeout: 30000, env: { ...process.env, ...env } });
    // read before the finally block deletes the scratch root
    const read = (id) => { try { return JSON.parse(fs.readFileSync(path.join(root, 'apps', 'vr', 'ArtSource', id, 'manifest.json'), 'utf8')); } catch { return null; } };
    const written = Object.fromEntries(ids.map((id) => [id, read(id)]));
    const manifest = (id) => written[id] ?? null;
    return { r, manifest };
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
}
{
  const base = runWriter({});
  check('writer: the harness itself is sound (stub passes, exit 0, both manifests written)', base.r.status === 0 && base.manifest('survey-pin') && base.manifest('fixture-kit'), `exit ${base.r.status}: ${(base.r.stderr ?? '').split('\n').find(Boolean) ?? ''}`);

  const third = runWriter({ STUB_IDS: 'survey-pin,fixture-kit,third-asset' }, ['survey-pin', 'fixture-kit', 'third-asset']);
  check('writer-notes: an asset with no NOTES entry is refused naming the id', third.r.status !== 0 && /third-asset/.test(third.r.stderr ?? '') && /NOTES/.test(third.r.stderr ?? ''), `exit ${third.r.status}: ${(third.r.stderr ?? '').split('\n').find((l) => /Error|third|NOTES/.test(l)) ?? ''}`);
  check('writer-notes: nothing is written before the reconcile refuses', !third.manifest('survey-pin'), 'survey-pin manifest was written');

  const bad = runWriter({ STUB_FAIL: 'poly_budget' });
  const m = bad.manifest('survey-pin');
  check('writer-exit: a false gate still lands in the manifest (the record is kept)', m && m.gates.poly_budget.pass === false, 'no manifest or gate not false');
  check('writer-exit: a written false gate makes the writer exit non-zero', bad.r.status !== 0, `exit ${bad.r.status}`);
}

// ---- source guard over scripts/art/**: no absolute machine path in code --------------------------------------------
// A literal drive path runs on one machine only. Comments are blanked to spaces first (line numbers stay true, and a
// header that merely TALKS about a path cannot satisfy or trip the match). The one allowed use is provenance: the lamp
// manifest records where its raw TRELLIS output lived, as a string it writes into the manifest, not a path it opens.
const PROVENANCE_ONLY = new Set(['lamp/write_manifest.mjs']);
const blankComments = (src) => src
  .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\r\n]/g, ' '))
  .split('\n').map((l) => l.replace(/(^|[^:'"\w])(\/\/.*)$/, (_, a, c) => a + ' '.repeat(c.length))).join('\n');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
{
  const hits = [];
  for (const f of walk(HERE).filter((x) => /\.mjs$/.test(x))) {
    const rel = path.relative(HERE, f).split(path.sep).join('/');
    if (PROVENANCE_ONLY.has(rel)) continue;
    blankComments(fs.readFileSync(f, 'utf8')).split('\n').forEach((line, i) => {
      for (const m of line.matchAll(/['"`][A-Za-z]:[\/][^'"`]*/g)) hits.push(`${rel}:${i + 1} ${m[0].slice(0, 60)}`);
    });
  }
  check('paths: no scripts/art script (but the provenance writer) names an absolute machine path', hits.length === 0, hits.join(' | '));
  const prov = blankComments(fs.readFileSync(path.join(HERE, 'lamp', 'write_manifest.mjs'), 'utf8'));
  check('paths: the allow-list is still needed (lamp/write_manifest.mjs still records its provenance paths)', /['"`][A-Za-z]:[\/]/.test(prov));
}

{
  const r = spawnSync(process.execPath, [TRELLIS, '303'], { encoding: 'utf8', timeout: 20000, env: { ...process.env, BP_COMFY_URL: DEAD } });
  check('trellis-seed: a valid seed passes the guard (it gets as far as the unreachable ComfyUI)', r.status !== 0 && !/seed must be an integer/.test(r.stderr ?? ''), `exit ${r.status}`);
}

console.log(`\n${failed ? `${failed} failed` : 'all passed'}`);
process.exit(failed ? 1 : 0);
